/// Position of the step and encounter generators.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Rng {
	pub step_seed: u8,
	pub step_index: u8,
	pub encounter_seed: u8,
	pub encounter_index: u8,
}

impl Rng {
	/// The generator state at the start of the game for the given seed.
	#[must_use]
	pub const fn new(seed: u8) -> Self {
		Self {
			step_seed: seed,
			step_index: 0,
			encounter_seed: seed.wrapping_mul(2),
			encounter_index: 0,
		}
	}

	/// Takes one step and reports whether it triggers an encounter on a map
	/// with the given encounter rate.
	pub fn step(&mut self, encounter_rate: u8) -> bool {
		self.step_index = self.step_index.wrapping_add(1);

		if self.step_index == 0 {
			self.step_seed = self.step_seed.wrapping_add(SEED_DELTA);
		}

		TABLE[usize::from(self.step_index)].wrapping_add(self.step_seed) < encounter_rate
	}

	/// The formation slot (0 to 7) the next encounter would use.
	#[must_use]
	pub const fn encounter_slot(&self) -> usize {
		let value = TABLE[self.encounter_index as usize].wrapping_add(self.encounter_seed);

		match value {
			0..43 => 0,
			43..86 => 1,
			86..129 => 2,
			129..172 => 3,
			172..204 => 4,
			204..236 => 5,
			236..252 => 6,
			_ => 7,
		}
	}

	/// Consumes the current encounter, advancing the encounter generator.
	pub const fn advance_encounter(&mut self) {
		self.encounter_index = self.encounter_index.wrapping_add(1);

		if self.encounter_index == 0 {
			self.encounter_seed = self.encounter_seed.wrapping_add(SEED_DELTA);
		}
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn table_is_a_permutation() {
		let mut seen = [false; 256];

		for value in TABLE {
			assert!(!seen[usize::from(value)]);
			seen[usize::from(value)] = true;
		}
	}

	#[test]
	fn seeds_advance_on_wraparound() {
		let mut rng = Rng::new(250);
		assert_eq!(rng.encounter_seed, 244);

		for _ in 0..256 {
			rng.step(0);
		}

		assert_eq!(rng.step_index, 0);
		assert_eq!(rng.step_seed, 250u8.wrapping_add(17));
	}
}
