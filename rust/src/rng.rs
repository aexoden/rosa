//! The FF4 random encounter generator.
//!
//! Encounters come from a fixed 256-byte table. Stepping advances a step index
//! (and, on wraparound, a step seed); an encounter happens when the table value
//! plus the seed falls below the map's encounter rate. A separate encounter
//! index and seed pick the formation slot within the map's encounter group.

/// Seeds advance by this amount each time their index wraps around.
const SEED_DELTA: u8 = 17;

/// Number of formation slots in an encounter group.
